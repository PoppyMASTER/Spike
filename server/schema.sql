-- SkySpike social server (Cloudflare D1 / SQLite)
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  tag INTEGER NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,
  avatar TEXT NOT NULL DEFAULT 'vex',
  color TEXT NOT NULL DEFAULT '#ffd642',
  bio TEXT NOT NULL DEFAULT '',
  team TEXT NOT NULL DEFAULT '[]',          -- showcase: [[id, lvl, stars], ...]
  ovr INTEGER NOT NULL DEFAULT 0,
  codex INTEGER NOT NULL DEFAULT 0,
  solo_w INTEGER NOT NULL DEFAULT 0,
  solo_l INTEGER NOT NULL DEFAULT 0,
  trophies TEXT NOT NULL DEFAULT '{}',
  xp INTEGER NOT NULL DEFAULT 0,
  elo INTEGER NOT NULL DEFAULT 1000,
  ranked_w INTEGER NOT NULL DEFAULT 0,
  ranked_l INTEGER NOT NULL DEFAULT 0,
  online_w INTEGER NOT NULL DEFAULT 0,
  online_l INTEGER NOT NULL DEFAULT 0,
  club_id INTEGER,
  status TEXT NOT NULL DEFAULT 'menu',
  created INTEGER NOT NULL,
  last_seen INTEGER NOT NULL,
  ip TEXT NOT NULL DEFAULT '',
  banned INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS users_name_tag ON users (name COLLATE NOCASE, tag);
CREATE INDEX IF NOT EXISTS users_elo ON users (elo DESC);

-- friendships: one row per direction; status 'pending' (a asked b) or 'friend'
CREATE TABLE IF NOT EXISTS friends (
  a INTEGER NOT NULL, b INTEGER NOT NULL, status TEXT NOT NULL, created INTEGER NOT NULL,
  PRIMARY KEY (a, b)
);
CREATE INDEX IF NOT EXISTS friends_b ON friends (b, status);

CREATE TABLE IF NOT EXISTS blocks (a INTEGER NOT NULL, b INTEGER NOT NULL, PRIMARY KEY (a, b));

CREATE TABLE IF NOT EXISTS messages (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  src INTEGER NOT NULL, dst INTEGER NOT NULL, text TEXT NOT NULL,
  created INTEGER NOT NULL, seen INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS messages_pair ON messages (src, dst, id);
CREATE INDEX IF NOT EXISTS messages_dst ON messages (dst, seen);

-- public rooms: 'global' and 'club:<id>'
CREATE TABLE IF NOT EXISTS chat (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  room TEXT NOT NULL, src INTEGER NOT NULL, text TEXT NOT NULL, created INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS chat_room ON chat (room, id);

CREATE TABLE IF NOT EXISTS invites (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  src INTEGER NOT NULL, dst INTEGER NOT NULL, code TEXT NOT NULL,
  created INTEGER NOT NULL, status TEXT NOT NULL DEFAULT 'open'
);
CREATE INDEX IF NOT EXISTS invites_dst ON invites (dst, status);

CREATE TABLE IF NOT EXISTS clubs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL, tag TEXT NOT NULL, descr TEXT NOT NULL DEFAULT '',
  color TEXT NOT NULL DEFAULT '#4fc3ff', owner INTEGER NOT NULL, open INTEGER NOT NULL DEFAULT 1,
  created INTEGER NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS clubs_name ON clubs (name COLLATE NOCASE);

CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  uid INTEGER NOT NULL, kind TEXT NOT NULL, data TEXT NOT NULL DEFAULT '{}', created INTEGER NOT NULL,
  likes INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS events_uid ON events (uid, id);
CREATE TABLE IF NOT EXISTS likes (event INTEGER NOT NULL, uid INTEGER NOT NULL, PRIMARY KEY (event, uid));

-- ranked matchmaking
CREATE TABLE IF NOT EXISTS queue (
  uid INTEGER PRIMARY KEY, elo INTEGER NOT NULL, joined INTEGER NOT NULL, seen INTEGER NOT NULL,
  match_id INTEGER
);
CREATE TABLE IF NOT EXISTS matches (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  host INTEGER NOT NULL, guest INTEGER NOT NULL, ranked INTEGER NOT NULL DEFAULT 1,
  code TEXT, winner INTEGER, score TEXT, created INTEGER NOT NULL, done INTEGER NOT NULL DEFAULT 0,
  delta INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS reports (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  src INTEGER NOT NULL, target INTEGER NOT NULL, reason TEXT NOT NULL, context TEXT NOT NULL DEFAULT '',
  created INTEGER NOT NULL
);
